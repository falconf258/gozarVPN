package app.gozarvpn.android.core

import android.content.Context
import app.gozarvpn.android.data.LogBuffer
import java.io.File
import java.net.HttpURLConnection
import java.net.InetSocketAddress
import java.net.URL

/**
 * "Iran direct" routing data: sing-box rule-sets of Iranian domains (geosite-ir) and IP ranges
 * (geoip-ir) from Chocolate4U/Iran-sing-box-rules (GPL-3.0). A snapshot ships in assets/rules;
 * an in-app update writes newer copies to files/rules, which then win.
 */
object IranRules {
    private val FILES = listOf("geosite-ir.srs", "geoip-ir.srs", "geosite-ir.txt")
    // jsDelivr mirrors the GitHub branch and is often reachable when GitHub itself is not
    private const val MIRROR = "https://cdn.jsdelivr.net/gh/Chocolate4U/Iran-sing-box-rules@rule-set/"

    fun dir(ctx: Context): File = File(ctx.filesDir, "rules").apply { mkdirs() }

    /** Copies the bundled snapshot in place the first time (or after an app update replaced it). */
    fun ensure(ctx: Context): File {
        val d = dir(ctx)
        val stamp = File(d, "bundled.json")
        val bundled = ctx.assets.open("rules/rules.json").bufferedReader().readText()
        val updated = File(d, "updated.json").exists()
        if (!updated && (!stamp.exists() || stamp.readText() != bundled || FILES.any { !File(d, it).exists() })) {
            for (f in FILES) ctx.assets.open("rules/$f").use { input -> File(d, f).outputStream().use { input.copyTo(it) } }
            stamp.writeText(bundled)
        }
        return d
    }

    /** Iranian IPv4 ranges (CIDR) for engines that route by IP (OpenVPN); the bundled snapshot. */
    fun cidrsV4(ctx: Context): List<String> = runCatching {
        ctx.assets.open("rules/geoip-ir.txt").bufferedReader().readLines().map { it.trim() }.filter { it.isNotEmpty() && ':' !in it }
    }.getOrDefault(emptyList())

    /** Date of the rules in use, for the settings card. */
    fun version(ctx: Context): String {
        val d = ensure(ctx)
        val f = File(d, "updated.json").takeIf { it.exists() } ?: File(d, "bundled.json")
        return Regex("\"date\"\\s*:\\s*\"([^\"]+)\"").find(f.readText())?.groupValues?.get(1) ?: "?"
    }

    /**
     * Downloads fresh rule-sets (through the engine's SOCKS port when given, so it works while
     * GitHub is blocked). A file is accepted only if it looks like a sing-box rule-set ("SRS"
     * header) and is not much smaller than the current one; the text list is regenerated by the
     * next app release, so the tester may lag behind until then.
     */
    fun update(ctx: Context, socksPort: Int?): String {
        val d = ensure(ctx)
        val got = mutableMapOf<String, ByteArray>()
        for (name in listOf("geosite-ir.srs", "geoip-ir.srs")) {
            val url = URL(MIRROR + name)
            val c = (if (socksPort != null) url.openConnection(java.net.Proxy(java.net.Proxy.Type.SOCKS, InetSocketAddress("127.0.0.1", socksPort)))
                else url.openConnection()) as HttpURLConnection
            c.connectTimeout = 15000; c.readTimeout = 30000
            val bytes = try { c.inputStream.readBytes() } finally { c.disconnect() }
            val old = File(d, name).length()
            require(bytes.size > 16 && String(bytes, 0, 3) == "SRS") { "فایل $name معتبر نیست" }
            require(bytes.size > old / 2) { "فایل $name از نسخه‌ی فعلی خیلی کوچک‌تر است" }
            got[name] = bytes
        }
        for ((name, bytes) in got) File(d, "$name.tmp").apply { writeBytes(bytes); renameTo(File(d, name)) }
        val date = java.text.SimpleDateFormat("yyyy-MM-dd", java.util.Locale.US).format(java.util.Date())
        File(d, "updated.json").writeText("{\"date\":\"$date\"}")
        LogBuffer.add("قوانین ایران به‌روز شد ($date)")
        return date
    }

    @Volatile private var suffixes: HashSet<String>? = null

    /** Why would [host] go direct? null = it goes through the VPN. */
    fun explain(ctx: Context, host: String, directList: List<String>, proxyList: List<String>): String? {
        val h = host.trim().lowercase().removePrefix("http://").removePrefix("https://").substringBefore('/').substringBefore(':').trimEnd('.')
        if (h.isEmpty()) return null
        fun inList(list: List<String>) = list.firstOrNull { e -> val s = e.trim().lowercase().trimStart('.'); s.isNotEmpty() && (h == s || h.endsWith(".$s")) }
        inList(proxyList)?.let { return null }
        inList(directList)?.let { return "در لیست «همیشه مستقیم» شما ($it)" }
        if (h == "ir" || h.endsWith(".ir")) return "دامنه‌ی ‎.ir"
        val set = suffixes ?: File(ensure(ctx), "geosite-ir.txt").readLines().map { it.trim() }.filter { it.isNotEmpty() }.toHashSet().also { suffixes = it }
        var cur = h
        while (true) {
            if (cur in set) return "در فهرست سایت‌های ایرانی ($cur)"
            val i = cur.indexOf('.')
            if (i < 0) return null
            cur = cur.substring(i + 1)
        }
    }
}
